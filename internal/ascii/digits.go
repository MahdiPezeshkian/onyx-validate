// Package ascii provides small ASCII helpers used by validators.
package ascii

// IsDigits reports whether s is non-empty and contains only ASCII digits.
func IsDigits(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return false
		}
	}
	return true
}

// IsAlphaNumUpper reports whether s contains only A-Z and 0-9.
func IsAlphaNumUpper(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if (c < 'A' || c > 'Z') && (c < '0' || c > '9') {
			return false
		}
	}
	return true
}
