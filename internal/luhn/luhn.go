// Package luhn implements the Luhn checksum algorithm.
package luhn

// Valid reports whether digits (ASCII '0'-'9' only) pass the Luhn check.
func Valid(digits string) bool {
	if digits == "" {
		return false
	}
	sum := 0
	alt := false
	for i := len(digits) - 1; i >= 0; i-- {
		c := digits[i]
		if c < '0' || c > '9' {
			return false
		}
		n := int(c - '0')
		if alt {
			n *= 2
			if n > 9 {
				n -= 9
			}
		}
		sum += n
		alt = !alt
	}
	return sum%10 == 0
}
